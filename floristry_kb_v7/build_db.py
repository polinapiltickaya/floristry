SCHEMA_SQL = """
PRAGMA foreign_keys = ON;

DROP TABLE IF EXISTS plant_occasions;
DROP TABLE IF EXISTS bouquet_occasions;
DROP TABLE IF EXISTS occasions;
DROP TABLE IF EXISTS resources;
DROP TABLE IF EXISTS shop_bouquets;
DROP TABLE IF EXISTS shops;
DROP TABLE IF EXISTS bouquet_composition;
DROP TABLE IF EXISTS bouquets;
DROP TABLE IF EXISTS plants;
DROP TABLE IF EXISTS styles;

CREATE TABLE plants (
    plant_id     INTEGER PRIMARY KEY AUTOINCREMENT,
    name_ru      VARCHAR(100) NOT NULL,
    name_latin   VARCHAR(100),
    category     VARCHAR(50),
    color        VARCHAR(50),
    season       VARCHAR(50),
    description  TEXT,
    care_info    TEXT,
    image_url    TEXT
);

CREATE TABLE bouquets (
    bouquet_id   INTEGER PRIMARY KEY AUTOINCREMENT,
    name         VARCHAR(150) NOT NULL,
    description  TEXT,
    style        VARCHAR(50),
    image_url    TEXT
);

CREATE TABLE bouquet_composition (
    bouquet_id   INTEGER NOT NULL REFERENCES bouquets(bouquet_id) ON DELETE CASCADE,
    plant_id     INTEGER NOT NULL REFERENCES plants(plant_id) ON DELETE RESTRICT,
    quantity     INTEGER NOT NULL DEFAULT 1,
    role         VARCHAR(30),
    PRIMARY KEY (bouquet_id, plant_id)
);

CREATE TABLE styles (
    style_id         INTEGER PRIMARY KEY AUTOINCREMENT,
    name             VARCHAR(100) NOT NULL,
    subtitle         VARCHAR(150),
    description      TEXT NOT NULL,
    characteristics  TEXT NOT NULL,
    usage_info       TEXT,
    image_url        TEXT
);

CREATE TABLE shops (
    shop_id        INTEGER PRIMARY KEY AUTOINCREMENT,
    name           VARCHAR(150) NOT NULL,
    city           VARCHAR(50) DEFAULT 'Гродно',
    instagram_url  TEXT NOT NULL,
    description    TEXT
);

CREATE TABLE shop_bouquets (
    shop_id      INTEGER NOT NULL REFERENCES shops(shop_id) ON DELETE CASCADE,
    bouquet_id   INTEGER NOT NULL REFERENCES bouquets(bouquet_id) ON DELETE CASCADE,
    PRIMARY KEY (shop_id, bouquet_id)
);

CREATE TABLE resources (
    resource_id  INTEGER PRIMARY KEY AUTOINCREMENT,
    type         VARCHAR(10) NOT NULL CHECK (type IN ('статья', 'видео')),
    title        VARCHAR(200) NOT NULL,
    url          TEXT NOT NULL,
    topic        VARCHAR(100)
);

CREATE TABLE occasions (
    occasion_id  INTEGER PRIMARY KEY AUTOINCREMENT,
    name         VARCHAR(100) NOT NULL
);

CREATE TABLE bouquet_occasions (
    bouquet_id   INTEGER NOT NULL REFERENCES bouquets(bouquet_id) ON DELETE CASCADE,
    occasion_id  INTEGER NOT NULL REFERENCES occasions(occasion_id) ON DELETE CASCADE,
    PRIMARY KEY (bouquet_id, occasion_id)
);

CREATE TABLE plant_occasions (
    plant_id     INTEGER NOT NULL REFERENCES plants(plant_id) ON DELETE CASCADE,
    occasion_id  INTEGER NOT NULL REFERENCES occasions(occasion_id) ON DELETE CASCADE,
    PRIMARY KEY (plant_id, occasion_id)
);
"""

